/**
 * سؤال خام واحد (كما في مصدر الكتاب).
 */
export interface RawQuestion {
  /** المعرّف الفريد */
  id: number;

  /** القسم في الكتاب */
  section: string;

  /** الزمن المستهدف [min, max] بالميلي ثانية */
  targetTime: [number, number];

  /** نص السؤال */
  question: string;

  /** شرح الحل خطوة بخطوة */
  solution: string;

  /** الإجابة الصحيحة كنص (قد يحتوي إشارة سالبة أو علامة عشرية) */
  result: string;
}

