import React from 'react';
import { motion } from 'framer-motion';

interface MultiRodAbacusProps {
  digits: number[];
  activeRods?: number[];
  unitRodIndex?: number;
  arcValue?: number;
  runningTotal?: number;
  columns?: number;
}

const MultiRodAbacus: React.FC<MultiRodAbacusProps> = ({
  digits = [0, 0, 0, 0, 0],
  activeRods = [],
  unitRodIndex = 4,
  arcValue,
  runningTotal,
  columns = 5,
}) => {
  const startX = 52;
  const endX = 268;
  const rodSpacing = columns > 1 ? (endX - startX) / (columns - 1) : 0;

  const labels =
    columns === 5
      ? ['ع.ك', 'ك', 'م', 'ع', 'آ']
      : ['ت', 'ك', 'م', 'ع', 'آ'].slice(5 - columns);

  let arcPath = '';
  let arcCenterX = 160;
  if (activeRods.length > 0) {
    const minRod = Math.min(...activeRods);
    const maxRod = Math.max(...activeRods);
    const x1 = startX + minRod * rodSpacing - 18;
    const x2 = startX + maxRod * rodSpacing + 18;
    arcCenterX = (x1 + x2) / 2;
    arcPath = `M ${x1} 172 Q ${arcCenterX} 182 ${x2} 172`;
  }

  const beadSpring = {
    type: 'spring' as const,
    stiffness: 500,
    damping: 30,
  };

  return (
    <div className="w-full flex items-center justify-center select-none">
      <svg
        viewBox="0 0 320 220"
        className="w-full h-auto max-w-[360px] drop-shadow-2xl"
        style={{ overflow: 'visible' }}
      >
        <defs>
          <linearGradient id="woodFrame" x1="0%" y1="0%" x2="100%" y2="100%">
            <stop offset="0%" stopColor="#78350f" />
            <stop offset="50%" stopColor="#572507" />
            <stop offset="100%" stopColor="#451a03" />
          </linearGradient>

          <linearGradient id="beamGrad" x1="0%" y1="0%" x2="100%" y2="0%">
            <stop offset="0%" stopColor="#fde68a" />
            <stop offset="50%" stopColor="#fbbf24" />
            <stop offset="100%" stopColor="#d4a017" />
          </linearGradient>

          <filter id="laser-glow" x="-30%" y="-30%" width="160%" height="160%">
            <feGaussianBlur stdDeviation="3.5" result="blur" />
            <feComposite in="SourceGraphic" in2="blur" operator="over" />
          </filter>
        </defs>

        {/* الإطار الخشبي */}
        <rect
          x="14" y="10" width="292" height="182" rx="12"
          fill="url(#woodFrame)"
          stroke="#92400e"
          strokeWidth="3"
        />
        <rect
          x="24" y="20" width="272" height="162" rx="8"
          fill="#090d16"
          fillOpacity="0.85"
        />

        {/* عدّاد المجموع */}
        {runningTotal !== undefined && (
          <g transform="translate(160, 32)">
            <rect
              x="-45" y="-11" width="90" height="20" rx="6"
              fill="#0f172a"
              stroke="#0ea5e9"
              strokeWidth="1"
              strokeOpacity="0.6"
            />
            <motion.text
              key={runningTotal}
              initial={{ opacity: 0, y: -3 }}
              animate={{ opacity: 1, y: 0 }}
              transition={{ duration: 0.15 }}
              x="0" y="3"
              textAnchor="middle"
              fill="#bae6fd"
              fontSize="12"
              fontWeight="800"
              fontFamily="monospace"
              style={{ fontVariantNumeric: 'tabular-nums' }}
            >
              {runningTotal}
            </motion.text>
          </g>
        )}

        {/* العارضة */}
        <rect
          x="20" y="84" width="280" height="6" rx="2"
          fill="url(#beamGrad)"
          stroke="#b45309"
          strokeWidth="1"
        />

        {/* الأعمدة والخرزات */}
        {Array.from({ length: columns }).map((_, i) => {
          const rodX = startX + i * rodSpacing;
          const isActiveRod = activeRods.includes(i);
          const isUnitRod = unitRodIndex === i;
          const digit = digits[i] ?? 0;
          const hasUpper = digit >= 5;
          const lowerVal = digit % 5;
          const upperY = hasUpper ? 64 : 36;

          return (
            <g
              key={i}
              opacity={isActiveRod ? 1 : 0.55}
              style={{ transition: 'opacity 0.2s ease' }}
            >
              <line
                x1={rodX} y1="26" x2={rodX} y2="178"
                stroke="#94a3b8"
                strokeWidth="3.5"
                strokeLinecap="round"
              />

              {isUnitRod && (
                <circle
                  cx={rodX} cy="87" r="3.5"
                  fill="#ef4444"
                  stroke="#991b1b"
                  strokeWidth="1"
                />
              )}

              {isActiveRod && (
                <motion.line
                  initial={{ opacity: 0.3 }}
                  animate={{ opacity: [0.3, 0.8, 0.3] }}
                  transition={{ repeat: Infinity, duration: 1.2 }}
                  x1={rodX} y1="26" x2={rodX} y2="178"
                  stroke="#38bdf8"
                  strokeWidth="5"
                  strokeLinecap="round"
                  filter="url(#laser-glow)"
                />
              )}

              {/* الجدة */}
              <motion.g
                initial={false}
                animate={{ y: upperY }}
                transition={beadSpring}
              >
                <rect
                  x={rodX - 21} y="0" width="42" height="18" rx="9"
                  fill={isActiveRod ? '#075985' : '#1e293b'}
                  stroke={isActiveRod ? '#7dd3fc' : '#334155'}
                  strokeWidth={isActiveRod ? 2 : 1}
                  filter={isActiveRod ? 'url(#laser-glow)' : undefined}
                />
                <rect
                  x={rodX - 14} y="3" width="28" height="3" rx="1.5"
                  fill={isActiveRod ? '#bae6fd' : '#475569'}
                  pointerEvents="none"
                />
              </motion.g>

              {/* الخرزات السفلية */}
              {[0, 1, 2, 3].map((b) => {
                const isPushedUp = b < lowerVal;
                const restingY = 104 + b * 18;
                const activeY = 90 + b * 18;
                const beadY = isPushedUp ? activeY : restingY;

                return (
                  <motion.g
                    key={b}
                    initial={false}
                    animate={{ y: beadY }}
                    transition={beadSpring}
                  >
                    <rect
                      x={rodX - 21} y="0" width="42" height="18" rx="9"
                      fill={isActiveRod ? '#075985' : '#1e293b'}
                      stroke={isActiveRod ? '#7dd3fc' : '#334155'}
                      strokeWidth={isActiveRod ? 2 : 1}
                      filter={isActiveRod ? 'url(#laser-glow)' : undefined}
                    />
                    <rect
                      x={rodX - 14} y="3" width="28" height="3" rx="1.5"
                      fill={isActiveRod ? '#bae6fd' : '#475569'}
                      pointerEvents="none"
                    />
                  </motion.g>
                );
              })}

              <text
                x={rodX} y="204"
                textAnchor="middle"
                fill={isActiveRod ? '#38bdf8' : '#94a3b8'}
                fontSize="11"
                fontWeight="bold"
              >
                {labels[i]}
              </text>
            </g>
          );
        })}

        {/* القوس */}
        {activeRods.length > 0 && arcPath && (
          <g>
            <path
              d={arcPath}
              fill="none"
              stroke="#38bdf8"
              strokeWidth="2.5"
              strokeLinecap="round"
              filter="url(#laser-glow)"
            />
            {arcValue !== undefined && (
              <g transform={`translate(${arcCenterX}, 180)`}>
                <rect
                  x="-18" y="-9" width="36" height="18" rx="6"
                  fill="#075985"
                  stroke="#38bdf8"
                  strokeWidth="1.5"
                />
                <text
                  x="0" y="3"
                  textAnchor="middle"
                  fill="#e0f2fe"
                  fontSize="11"
                  fontWeight="900"
                  fontFamily="monospace"
                  style={{ fontVariantNumeric: 'tabular-nums' }}
                >
                  {String(arcValue).padStart(2, '0')}
                </text>
              </g>
            )}
          </g>
        )}
      </svg>
    </div>
  );
};

export default MultiRodAbacus;